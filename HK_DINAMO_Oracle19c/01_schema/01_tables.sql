WHENEVER SQLERROR EXIT SQL.SQLCODE

-- 1. Календарное измерение. TIME_ID имеет формат YYYYMMDD.
CREATE TABLE dim_time (
    time_id       NUMBER(8) CONSTRAINT pk_dim_time PRIMARY KEY,
    full_date     DATE NOT NULL,
    day_of_week   VARCHAR2(20 CHAR) NOT NULL,
    day_num       NUMBER(2) NOT NULL,
    month_num     NUMBER(2) NOT NULL,
    month_name    VARCHAR2(20 CHAR) NOT NULL,
    quarter_num   NUMBER(1) NOT NULL,
    year_num      NUMBER(4) NOT NULL,
    season        VARCHAR2(9 CHAR) NOT NULL,
    CONSTRAINT uq_dim_time_date UNIQUE (full_date),
    CONSTRAINT ck_dim_time_day CHECK (day_num BETWEEN 1 AND 31),
    CONSTRAINT ck_dim_time_month CHECK (month_num BETWEEN 1 AND 12),
    CONSTRAINT ck_dim_time_quarter CHECK (quarter_num BETWEEN 1 AND 4),
    CONSTRAINT ck_dim_time_year CHECK (year_num BETWEEN 1900 AND 9999),
    CONSTRAINT ck_dim_time_key CHECK (time_id = TO_NUMBER(TO_CHAR(full_date,'YYYYMMDD')))
);
COMMENT ON TABLE dim_time IS 'Календарное измерение для OLAP-анализа по датам и хоккейным сезонам';
COMMENT ON COLUMN dim_time.time_id IS 'Ключ календарной даты в формате YYYYMMDD';
COMMENT ON COLUMN dim_time.season IS 'Хоккейный сезон, например 2026/2027';

-- 2. Справочник стадионов.
CREATE TABLE dim_stadium (
    stadium_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
               CONSTRAINT pk_dim_stadium PRIMARY KEY,
    name       VARCHAR2(100 CHAR) NOT NULL,
    city       VARCHAR2(50 CHAR) NOT NULL,
    capacity   NUMBER(7) NOT NULL,
    CONSTRAINT uq_dim_stadium_name_city UNIQUE (name, city),
    CONSTRAINT ck_dim_stadium_capacity CHECK (capacity > 0)
);
COMMENT ON TABLE dim_stadium IS 'Справочник стадионов и арен';

-- 3. Сектора стадионов.
CREATE TABLE dim_sector (
    sector_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                CONSTRAINT pk_dim_sector PRIMARY KEY,
    stadium_id  NUMBER NOT NULL,
    sector_code VARCHAR2(50 CHAR) NOT NULL,
    category    VARCHAR2(20 CHAR) NOT NULL,
    capacity    NUMBER(5) NOT NULL,
    CONSTRAINT fk_sector_stadium FOREIGN KEY (stadium_id)
        REFERENCES dim_stadium(stadium_id),
    CONSTRAINT uq_sector_stadium_code UNIQUE (stadium_id, sector_code),
    CONSTRAINT ck_dim_sector_capacity CHECK (capacity BETWEEN 1 AND 99999),
    CONSTRAINT ck_dim_sector_category CHECK
        (category IN ('VIP','STANDARD','FAN','GUEST','OTHER'))
);
COMMENT ON TABLE dim_sector IS 'Сектора стадионов с вместимостью и категорией';

-- 4. Справочник игроков.
CREATE TABLE dim_player (
    player_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                  CONSTRAINT pk_dim_player PRIMARY KEY,
    first_name    VARCHAR2(50 CHAR) NOT NULL,
    last_name     VARCHAR2(50 CHAR) NOT NULL,
    position      VARCHAR2(15 CHAR) NOT NULL,
    jersey_number NUMBER(2),
    birth_date    DATE,
    country       VARCHAR2(50 CHAR),
    height_cm     NUMBER(3),
    weight_kg     NUMBER(3),
    is_active     CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT ck_dim_player_position CHECK
        (position IN ('GOALTENDER','DEFENDER','FORWARD')),
    CONSTRAINT ck_dim_player_jersey CHECK
        (jersey_number IS NULL OR jersey_number BETWEEN 0 AND 99),
    CONSTRAINT ck_dim_player_height CHECK
        (height_cm IS NULL OR height_cm BETWEEN 100 AND 250),
    CONSTRAINT ck_dim_player_weight CHECK
        (weight_kg IS NULL OR weight_kg BETWEEN 30 AND 200),
    CONSTRAINT ck_dim_player_active CHECK (is_active IN ('Y','N'))
);
COMMENT ON TABLE dim_player IS 'Справочник игроков хоккейного клуба';
COMMENT ON COLUMN dim_player.position IS 'GOALTENDER — вратарь; DEFENDER — защитник; FORWARD — нападающий';
COMMENT ON COLUMN dim_player.is_active IS 'Y — активный игрок; N — неактивный игрок';

-- 5. Матчи клуба.
CREATE TABLE dim_match (
    match_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                  CONSTRAINT pk_dim_match PRIMARY KEY,
    match_date    DATE NOT NULL,
    time_id       NUMBER(8) NOT NULL,
    opponent_name VARCHAR2(100 CHAR) NOT NULL,
    stadium_id    NUMBER NOT NULL,
    is_home       CHAR(1) NOT NULL,
    goals_for     NUMBER(2),
    goals_against NUMBER(2),
    match_status  VARCHAR2(15 CHAR) DEFAULT 'SCHEDULED' NOT NULL,
    CONSTRAINT fk_match_time FOREIGN KEY (time_id) REFERENCES dim_time(time_id),
    CONSTRAINT fk_match_stadium FOREIGN KEY (stadium_id) REFERENCES dim_stadium(stadium_id),
    CONSTRAINT ck_dim_match_home CHECK (is_home IN ('Y','N')),
    CONSTRAINT ck_dim_match_goals CHECK
       ((goals_for IS NULL AND goals_against IS NULL) OR
        (goals_for IS NOT NULL AND goals_against IS NOT NULL AND
         goals_for >= 0 AND goals_against >= 0)),
    CONSTRAINT ck_dim_match_status CHECK
       (match_status IN ('SCHEDULED','COMPLETED','CANCELLED')),
    CONSTRAINT ck_dim_match_completed CHECK
       (match_status <> 'COMPLETED' OR
        (goals_for IS NOT NULL AND goals_against IS NOT NULL))
);
COMMENT ON TABLE dim_match IS 'Матчи: дата, соперник, арена, статус и итоговый счёт';

-- 6. Болельщики и покупатели.
CREATE TABLE dim_fan (
    fan_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                      CONSTRAINT pk_dim_fan PRIMARY KEY,
    first_name        VARCHAR2(50 CHAR) NOT NULL,
    last_name         VARCHAR2(50 CHAR) NOT NULL,
    email             VARCHAR2(100 CHAR),
    phone             VARCHAR2(20 CHAR),
    city              VARCHAR2(50 CHAR),
    registration_date DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT uq_dim_fan_email UNIQUE (email)
);
COMMENT ON TABLE dim_fan IS 'Справочник болельщиков и покупателей';

-- 7. Каталог клубной атрибутики.
CREATE TABLE dim_merch (
    merch_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                CONSTRAINT pk_dim_merch PRIMARY KEY,
    name        VARCHAR2(100 CHAR) NOT NULL,
    category    VARCHAR2(50 CHAR) NOT NULL,
    price       NUMBER(10,2) NOT NULL,
    description VARCHAR2(500 CHAR),
    is_active   CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT ck_dim_merch_price CHECK (price >= 0),
    CONSTRAINT ck_dim_merch_active CHECK (is_active IN ('Y','N'))
);
COMMENT ON TABLE dim_merch IS 'Каталог товаров клубной атрибутики';

-- 8. Билеты. Одна строка — одно место на конкретный матч.
CREATE TABLE tickets (
    ticket_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                   CONSTRAINT pk_tickets PRIMARY KEY,
    match_id       NUMBER NOT NULL,
    sector_id      NUMBER NOT NULL,
    seat_row       NUMBER(3) NOT NULL,
    seat_number    NUMBER(3) NOT NULL,
    price          NUMBER(10,2) NOT NULL,
    status         VARCHAR2(10 CHAR) DEFAULT 'FREE' NOT NULL,
    fan_id         NUMBER,
    sale_time_id   NUMBER(8),
    reserved_by    NUMBER,
    reserved_until DATE,
    created_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_ticket_match FOREIGN KEY (match_id) REFERENCES dim_match(match_id),
    CONSTRAINT fk_ticket_sector FOREIGN KEY (sector_id) REFERENCES dim_sector(sector_id),
    CONSTRAINT fk_ticket_fan FOREIGN KEY (fan_id) REFERENCES dim_fan(fan_id),
    CONSTRAINT fk_ticket_sale_time FOREIGN KEY (sale_time_id) REFERENCES dim_time(time_id),
    CONSTRAINT fk_ticket_reserved_by FOREIGN KEY (reserved_by) REFERENCES dim_fan(fan_id),
    CONSTRAINT uq_ticket_seat UNIQUE (match_id, sector_id, seat_row, seat_number),
    CONSTRAINT ck_ticket_seat CHECK (seat_row > 0 AND seat_number > 0),
    CONSTRAINT ck_ticket_price CHECK (price >= 0),
    CONSTRAINT ck_ticket_status CHECK (status IN ('FREE','RESERVED','SOLD','RETURNED')),
    CONSTRAINT ck_ticket_state_fields CHECK (
       (status = 'FREE' AND fan_id IS NULL AND sale_time_id IS NULL
          AND reserved_by IS NULL AND reserved_until IS NULL)
       OR
       (status = 'RESERVED' AND fan_id IS NULL AND sale_time_id IS NULL
          AND reserved_by IS NOT NULL AND reserved_until IS NOT NULL)
       OR
       (status = 'SOLD' AND fan_id IS NOT NULL AND sale_time_id IS NOT NULL
          AND reserved_by IS NULL AND reserved_until IS NULL)
       OR
       (status = 'RETURNED' AND reserved_by IS NULL AND reserved_until IS NULL)
    )
);
COMMENT ON TABLE tickets IS 'Билеты: учёт мест, продаж, возвратов и временного резервирования';
COMMENT ON COLUMN tickets.status IS 'FREE — свободен; RESERVED — зарезервирован; SOLD — продан; RETURNED — возвращён';
COMMENT ON COLUMN tickets.sale_time_id IS 'Дата продажи для анализа выручки по периодам';
COMMENT ON COLUMN tickets.reserved_until IS 'Дата и время окончания резерва';

-- 9. Продажи атрибутики. Одна строка — одна товарная позиция.
CREATE TABLE merch_orders (
    order_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                 CONSTRAINT pk_merch_orders PRIMARY KEY,
    merch_id     NUMBER NOT NULL,
    fan_id       NUMBER NOT NULL,
    time_id      NUMBER(8) NOT NULL,
    quantity     NUMBER(5) NOT NULL,
    unit_price   NUMBER(10,2) NOT NULL,
    total_amount NUMBER(12,2) GENERATED ALWAYS AS (quantity * unit_price) VIRTUAL,
    status       VARCHAR2(20 CHAR) DEFAULT 'COMPLETED' NOT NULL,
    CONSTRAINT fk_merch_order_merch FOREIGN KEY (merch_id) REFERENCES dim_merch(merch_id),
    CONSTRAINT fk_merch_order_fan FOREIGN KEY (fan_id) REFERENCES dim_fan(fan_id),
    CONSTRAINT fk_merch_order_time FOREIGN KEY (time_id) REFERENCES dim_time(time_id),
    CONSTRAINT ck_merch_order_qty CHECK (quantity > 0),
    CONSTRAINT ck_merch_order_price CHECK (unit_price >= 0),
    CONSTRAINT ck_merch_order_status CHECK (status IN ('PENDING','COMPLETED','CANCELLED'))
);
COMMENT ON TABLE merch_orders IS 'Факты продаж атрибутики; одна строка — один вид товара в заказе';
COMMENT ON COLUMN merch_orders.total_amount IS 'Виртуальный столбец: quantity * unit_price';

-- 10. Статистика игроков по матчам.
CREATE TABLE fact_match_stats (
    stat_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                    CONSTRAINT pk_fact_match_stats PRIMARY KEY,
    match_id        NUMBER NOT NULL,
    player_id       NUMBER NOT NULL,
    time_id         NUMBER(8) NOT NULL,
    goals           NUMBER(2) DEFAULT 0 NOT NULL,
    assists         NUMBER(2) DEFAULT 0 NOT NULL,
    points          NUMBER(3) GENERATED ALWAYS AS (goals + assists) VIRTUAL,
    penalty_minutes NUMBER(3) DEFAULT 0 NOT NULL,
    plus_minus      NUMBER(3) DEFAULT 0 NOT NULL,
    shots           NUMBER(3) DEFAULT 0 NOT NULL,
    time_on_ice_sec NUMBER(5) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_stats_match FOREIGN KEY (match_id) REFERENCES dim_match(match_id),
    CONSTRAINT fk_stats_player FOREIGN KEY (player_id) REFERENCES dim_player(player_id),
    CONSTRAINT fk_stats_time FOREIGN KEY (time_id) REFERENCES dim_time(time_id),
    CONSTRAINT uq_match_player UNIQUE (match_id, player_id),
    CONSTRAINT ck_stats_goals CHECK (goals >= 0),
    CONSTRAINT ck_stats_assists CHECK (assists >= 0),
    CONSTRAINT ck_stats_penalty CHECK (penalty_minutes >= 0),
    CONSTRAINT ck_stats_shots CHECK (shots >= 0),
    CONSTRAINT ck_stats_ice_time CHECK (time_on_ice_sec >= 0)
);
COMMENT ON TABLE fact_match_stats IS 'Статистика игроков по матчам для анализа результативности';
COMMENT ON COLUMN fact_match_stats.points IS 'Виртуальный столбец: голы плюс передачи';

-- 11. Учётные записи приложения. FAN_ID связывает профиль пользователя
-- приложения с записью болельщика для операций с билетами и избранным.
CREATE TABLE app_users (
    user_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                  CONSTRAINT pk_app_users PRIMARY KEY,
    username      VARCHAR2(50 CHAR) NOT NULL,
    password_hash VARCHAR2(200 CHAR) NOT NULL,
    email         VARCHAR2(100 CHAR) NOT NULL,
    role          VARCHAR2(20 CHAR) NOT NULL,
    fan_id        NUMBER,
    db_username   VARCHAR2(128 CHAR),
    is_active     CHAR(1) DEFAULT 'Y' NOT NULL,
    created_at    DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_app_users_fan FOREIGN KEY (fan_id) REFERENCES dim_fan(fan_id),
    CONSTRAINT uq_app_users_username UNIQUE (username),
    CONSTRAINT uq_app_users_email UNIQUE (email),
    CONSTRAINT uq_app_users_fan UNIQUE (fan_id),
    CONSTRAINT uq_app_users_db_user UNIQUE (db_username),
    CONSTRAINT ck_app_users_role CHECK (role IN ('MAIN_ADMIN','ADMIN','USER')),
    CONSTRAINT ck_app_users_active CHECK (is_active IN ('Y','N'))
);
COMMENT ON TABLE app_users IS 'Прикладные учётные записи; не заменяют учётные записи Oracle';
COMMENT ON COLUMN app_users.password_hash IS 'Хеш пароля, сформированный прикладной системой; открытый пароль не хранится';
COMMENT ON COLUMN app_users.fan_id IS 'Необязательная связь прикладной учётной записи с профилем болельщика';
COMMENT ON COLUMN app_users.db_username IS 'Необязательная привязка к Oracle-пользователю для проверки демонстрационного подключения';

-- 12. Связь болельщиков с избранными игроками для оценки популярности.
CREATE TABLE fan_player_favorites (
    favorite_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                CONSTRAINT pk_fan_player_favorites PRIMARY KEY,
    fan_id      NUMBER NOT NULL,
    player_id   NUMBER NOT NULL,
    created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_favorites_fan FOREIGN KEY (fan_id) REFERENCES dim_fan(fan_id),
    CONSTRAINT fk_favorites_player FOREIGN KEY (player_id) REFERENCES dim_player(player_id),
    CONSTRAINT uq_fan_player_favorite UNIQUE (fan_id, player_id)
);
COMMENT ON TABLE fan_player_favorites IS 'Избранные игроки; используется для оценки популярности';

